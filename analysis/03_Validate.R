# Final consistency checks; run after scripts 01 and 02.
td<-'results/tables'
ed<-'results/extended_tables'
readtab<-function(n,folder=td)read.delim(file.path(folder,paste0(n,'.tsv')),check.names=FALSE)
d<-readRDS('work/analysis/prepared.rds')
forms<-readRDS('work/analysis/formulas.rds')
r<-readtab('model_results');di<-readtab('model_diagnostics')
facts<-readtab('manuscript_facts');fact<-setNames(facts$value,facts$statistic)
inc<-readtab('income_imputation_counts')
m<-readtab('standardized_prevalence_and_contrasts',ed)
checks<-list()
check<-function(name,ok,note=''){checks[[name]]<<-data.frame(check=name,passed=isTRUE(ok),note=note);if(!isTRUE(ok))stop('Validation failed: ',name)}
check('one_common_sample_for_M0_to_M4',length(unique(r$n[r$model %in% paste0('M',0:4)]))==1)
check('same_main_events',all(r$events[r$model %in% paste0('M',0:4)]==fact['common_events']))
check('common_sample_uses_only_required_M4_covariates',identical(d$common,d$older & complete.cases(d[setdiff(all.vars(forms$M4),'poverty')])) )
check('comparison_exposures_do_not_restrict_main_sample',!any(c('voice','speech','communication') %in% all.vars(forms$M4)))
check('M4_adds_depressive_feelings_to_M3',setequal(setdiff(all.vars(forms$M4),all.vars(forms$M3)),'depression'))
check('M2_individual_comorbidity_variables',all(c('mi','lung','arthritis','diabetes','cancer','stroke','dementia') %in% all.vars(forms$M2)))
check('all_models_converged',all(di$converged))
check('positive_coefficient_covariance',all(di$minimum_covariance_eigenvalue>0))
check('finite_estimates_CIs',all(is.finite(as.matrix(r[c('estimate','lower','upper','se_log','df')]))))
check('income_full_plus_bracket_equals_total',all(inc$income_fully_imputed_n+inc$income_bracket_imputed_n==inc$income_imputed_n))
check('facts_income_matches_count_table',inc$income_imputed_n[inc$population=='common']==fact['income_imputed_n'])
check('common_counts_sum',fact['common_exposed_n']+fact['common_unexposed_n']==fact['common_n'] && fact['common_exposed_events']+fact['common_unexposed_events']==fact['common_events'])
check('primary_2by2_minimum_cell',min(readtab('exposure_outcome_common')$Freq)>=20)
check('severity_minimum_cell',min(readtab('severity_outcome_common')$Freq)>=20)
check('margin_probabilities_valid',all(m$estimate[m$measure %in% c('prevalence_no_problem','prevalence_problem')]>0 & m$estimate[m$measure %in% c('prevalence_no_problem','prevalence_problem')]<1))
check('margin_n_same_as_regression',all(m$n==fact['common_n']))
check('IPW_linearization_covariance_check',max(readtab('joint_score_validation',ed)$max_covariance_difference)<1e-7)
check('ordinal_joint_covariance_check',max(readtab('threshold_covariance_validation',ed)$max_covariance_difference)<1e-7)
check('ordinal_contrast_count',nrow(readtab('proportional_odds_diagnostics',ed))==3*di$nonintercept_parameters[di$model=='M3'])
check('table1_has_all_group_counts',all(readtab('manuscript_table1')$denominator %in% c(fact['common_exposed_n'],fact['common_unexposed_n'])))
check('M4_events_per_parameter_reported',abs(di$events_per_parameter[di$model=='M4']-9.9)<1e-12,'M4 contains 40 nonintercept parameters and 396 outcomes (9.90 events per parameter); convergence and sparse-cell diagnostics are reported.')
out<-do.call(rbind,checks)
write.table(out,'results/analysis_validation.tsv',sep='\t',row.names=FALSE,quote=FALSE)
cat('ALL',nrow(out),'FINAL ANALYSIS CHECKS PASSED\n')
